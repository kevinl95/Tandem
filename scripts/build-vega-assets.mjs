// Copies the web receiver into the Vega app's assets directory.
//
// The Vega WebView loads pages from file:///pkg/assets, where Chromium refuses
// ES module scripts (opaque "null" origin), so the receiver modules are
// flattened into a single classic script.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
export const DEFAULT_OUT_DIR = path.join(repoRoot, "vega-app", "assets");
export const RECEIVER_BUNDLE_NAME = "tandem-receiver.js";

// Dependency order: each module may only reference modules listed before it.
const RECEIVER_MODULES = [
  "src/receiver/config.js",
  "src/receiver/receiver.js",
  "public/receiver/app.js",
];

function replaceExactlyOnce(source, searchValue, replaceValue, label) {
  const occurrences = source.split(searchValue).length - 1;
  if (occurrences !== 1) {
    throw new Error(
      `${label}: expected exactly one occurrence of ${JSON.stringify(searchValue)}, found ${occurrences}`,
    );
  }
  return source.replace(searchValue, replaceValue);
}

export function toClassicScript(source, label) {
  const stripped = source
    .replace(/^import\s[\s\S]*?\sfrom\s+["'][^"']+["'];?[ \t]*$/gm, "")
    .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let)\b)/gm, "");

  if (/^\s*(?:import|export)\b/m.test(stripped)) {
    throw new Error(`${label}: unsupported import/export syntax left after flattening`);
  }

  return stripped;
}

export async function bundleReceiver() {
  const parts = await Promise.all(
    RECEIVER_MODULES.map(async (modulePath) => {
      const source = await readFile(path.join(repoRoot, modulePath), "utf8");
      return `// ---- ${modulePath}\n${toClassicScript(source, modulePath)}`;
    }),
  );

  return `// Generated by scripts/build-vega-assets.mjs. Do not edit.\n(() => {\n"use strict";\n${parts.join("\n")}\n})();\n`;
}

// Receiver settings baked into the Vega package: TANDEM_SIGNALING_URL wins,
// otherwise tandem.config.json as written by `npm run deploy:signaling`.
export async function loadReceiverConfig({ env = process.env } = {}) {
  let fileConfig = {};
  try {
    fileConfig = JSON.parse(await readFile(path.join(repoRoot, "tandem.config.json"), "utf8"));
  } catch (error) {
    if (error.code !== "ENOENT") {
      throw error;
    }
  }

  return {
    signalingEndpoint: env.TANDEM_SIGNALING_URL ?? fileConfig.signalingEndpoint ?? "",
    stunServerUrl: env.TANDEM_STUN_URL ?? fileConfig.stunServerUrl ?? "",
  };
}

function inlineConfigScript(config) {
  // Escape "<" so config values can never close the script element.
  const json = JSON.stringify(config).replace(/</g, "\\u003c");
  return `<script>window.TANDEM_CONFIG = ${json};</script>`;
}

export async function buildVegaAssets({ outDir = DEFAULT_OUT_DIR, config } = {}) {
  await mkdir(outDir, { recursive: true });
  const receiverConfig = config ?? (await loadReceiverConfig());

  const receiverHtml = replaceExactlyOnce(
    replaceExactlyOnce(
      await readFile(path.join(repoRoot, "public/receiver/index.html"), "utf8"),
      '<script type="module" src="./app.js"></script>',
      `${inlineConfigScript(receiverConfig)}\n    <script src="./${RECEIVER_BUNDLE_NAME}"></script>`,
      "receiver index.html",
    ),
    'href="../probe/"',
    'href="./probe.html"',
    "receiver index.html",
  );

  const probeHtml = replaceExactlyOnce(
    await readFile(path.join(repoRoot, "public/probe/index.html"), "utf8"),
    'href="../receiver/"',
    'href="./index.html"',
    "probe index.html",
  );

  const outputs = {
    "index.html": receiverHtml,
    [RECEIVER_BUNDLE_NAME]: await bundleReceiver(),
    "probe.html": probeHtml,
    "probe.js": await readFile(path.join(repoRoot, "public/probe/probe.js"), "utf8"),
  };

  await Promise.all(
    Object.entries(outputs).map(([name, contents]) =>
      writeFile(path.join(outDir, name), contents),
    ),
  );

  return Object.keys(outputs);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const config = await loadReceiverConfig();
  const written = await buildVegaAssets({ outDir: process.argv[2], config });
  console.log(`Wrote ${written.join(", ")} to ${process.argv[2] ?? DEFAULT_OUT_DIR}`);
  if (!config.signalingEndpoint) {
    console.warn("No signaling endpoint configured: run `npm run deploy:signaling` or set TANDEM_SIGNALING_URL.");
  }
}
